#ifndef MIDDLEEND_LLVM_INST_MEMORY_GEP_H
#define MIDDLEEND_LLVM_INST_MEMORY_GEP_H
#include "middleend/llvm/inst/inst.h"
#include "utils/type/type.h"
namespace middleend::llvm::inst {
class GetElementPtrInst : public Instruction {
 public:
  // Interfaces to get gep information

  // Override the Emit and Verify functions
  auto Emit(std::ofstream *out) const -> void override;
  auto Verify(context::CompilerContext *context) const -> bool override;

 private:
  explicit GetElementPtrInst(utils::Operand *base_ptr, const std::vector<utils::Operand *> &indices)
      : Instruction(OpKind::GetElementPtr) {
    operands_.reserve(indices.size() + 1);
    operands_.emplace_back(base_ptr);
    for (auto &index : indices) {
      operands_.emplace_back(index);
    }
  }

  static auto Create(context::LLVMIRContext *context, type::Type *result_type, utils::Operand *base_ptr,
                     const std::vector<utils::Operand *> &indices) -> GetElementPtrInst *;
  friend class utils::factory::InstFactory;

  /**
   * @brief GEP instruction is like:
   * %ptr = getelementptr [dim1 x [dim2 x ...]], ptr, base , i32 0, i32 <index1>, i32 <index2>, ...
   */
  // dimensions get from the base ptr
  /**
   * @note: base_ptr_ must be generated by alloca instruction
   */
};

}  // namespace middleend::llvm::inst

#endif