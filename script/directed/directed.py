#!/usr/bin/env python3
"""Directed middle-end tests: IR-dump assertions + qemu correctness.

Each test is a .sy file under testcases/directed/<group>/. Assertions are
written as `//!` comment directives inside the test and are checked against
the -O1 IR dump; correctness is checked by cross-compiling and running under
qemu for both targets at -O0 and -O1, comparing stdout+exit-code against a
golden output (a committed .out file, or one generated by compiling the test
as C on the host with sylib).

Directives:
  //! STAGE: baseir|llvm            dump stage for all checks (default baseir)
  //! CHECK: <ere>                  some dump line matches <ere>
  //! CHECK-NOT: <ere>              no dump line matches <ere>
  //! CHECK-COUNT: <n> :: <ere>     exactly <n> dump lines match <ere>
  //! CHECK-STATS: <ere>            pass statistics contain a matching line
  //! CHECK-STATS-NOT: <ere>        pass statistics contain no matching line
  //! CHECK-BLOCK: <bere> :: <ere>  a block whose label matches <bere> has a
                                    line matching <ere>
  //! CHECK-BLOCK-NOT: <bere> :: <ere>
                                    no block whose label matches <bere> has a
                                    line matching <ere>

Usage:
  python3 script/directed/directed.py [--filter substr] [--targets riscv,aarch64]
                                      [--opts 0,1] [--ir-only] [--verbose]
"""
import argparse
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
COMPILER = os.path.join(ROOT, "bin", "compiler")
TESTDIR = os.path.join(ROOT, "testcases", "directed")
WORK = os.path.join(ROOT, "bench", "dwork")
SYLIB_H = os.path.join(ROOT, "libs", "sylib.h")
SYLIB_C = os.path.join(ROOT, "libs", "sylib.c")

TARGETS = {
    "riscv": {"flag": "-riscv", "gcc": "riscv64-linux-gnu-gcc", "qemu": "qemu-riscv64"},
    "aarch64": {"flag": "-aarch64", "gcc": "aarch64-linux-gnu-gcc", "qemu": "qemu-aarch64"},
}

BLOCK_RE = re.compile(r"^\s*%([A-Za-z_][A-Za-z0-9_.]*)\s*\([^)]*\)\s*\{\s*$")
DIRECTIVE_RE = re.compile(r"^\s*//!\s*([A-Z-]+):\s*(.*?)\s*$")


class Failure(Exception):
    pass


def run(cmd, stdin_path=None, timeout=60, env=None):
    stdin = open(stdin_path, "rb") if stdin_path else subprocess.DEVNULL
    try:
        return subprocess.run(cmd, stdin=stdin, stdout=subprocess.PIPE,
                              stderr=subprocess.PIPE, timeout=timeout, env=env)
    finally:
        if stdin_path:
            stdin.close()


def parse_directives(sy_path):
    stage = "baseir"
    checks = []  # (kind, arg1, arg2, lineno)
    with open(sy_path, encoding="utf-8") as f:
        for lineno, line in enumerate(f, 1):
            m = DIRECTIVE_RE.match(line)
            if not m:
                continue
            kind, rest = m.group(1), m.group(2)
            if kind == "STAGE":
                if rest not in ("baseir", "llvm"):
                    raise Failure(f"line {lineno}: bad STAGE '{rest}'")
                stage = rest
            elif kind in ("CHECK", "CHECK-NOT", "CHECK-STATS", "CHECK-STATS-NOT"):
                checks.append((kind, rest, None, lineno))
            elif kind == "CHECK-COUNT":
                n, sep, ere = rest.partition("::")
                if not sep:
                    raise Failure(f"line {lineno}: CHECK-COUNT needs '<n> :: <ere>'")
                checks.append((kind, ere.strip(), int(n.strip()), lineno))
            elif kind in ("CHECK-BLOCK", "CHECK-BLOCK-NOT"):
                bere, sep, ere = rest.partition("::")
                if not sep:
                    raise Failure(f"line {lineno}: {kind} needs '<blockere> :: <ere>'")
                checks.append((kind, bere.strip(), ere.strip(), lineno))
            else:
                raise Failure(f"line {lineno}: unknown directive '{kind}'")
    return stage, checks


def split_blocks(dump_lines):
    """Map block label -> list of lines, scoped until the next block header."""
    blocks = {}
    current = None
    for line in dump_lines:
        m = BLOCK_RE.match(line)
        if m:
            current = m.group(1)
            blocks.setdefault(current, [])
            continue
        if current is not None:
            blocks[current].append(line)
    return blocks


def apply_checks(checks, dump_lines, blocks, stats_lines):
    errors = []
    for kind, a, b, lineno in checks:
        if kind == "CHECK":
            if not any(re.search(a, ln) for ln in dump_lines):
                errors.append(f"line {lineno}: CHECK '{a}' not found in dump")
        elif kind == "CHECK-NOT":
            hits = [ln.strip() for ln in dump_lines if re.search(a, ln)]
            if hits:
                errors.append(f"line {lineno}: CHECK-NOT '{a}' matched: {hits[0]}")
        elif kind == "CHECK-COUNT":
            got = sum(1 for ln in dump_lines if re.search(a, ln))
            if got != b:
                errors.append(f"line {lineno}: CHECK-COUNT '{a}' expected {b}, got {got}")
        elif kind == "CHECK-STATS":
            if not any(re.search(a, ln) for ln in stats_lines):
                errors.append(f"line {lineno}: CHECK-STATS '{a}' not found in statistics")
        elif kind == "CHECK-STATS-NOT":
            hits = [ln.strip() for ln in stats_lines if re.search(a, ln)]
            if hits:
                errors.append(f"line {lineno}: CHECK-STATS-NOT '{a}' matched: {hits[0]}")
        elif kind == "CHECK-BLOCK":
            names = [n for n in blocks if re.search(a, n)]
            if not names:
                errors.append(f"line {lineno}: CHECK-BLOCK no block matches '{a}'")
            elif not any(re.search(b, ln) for n in names for ln in blocks[n]):
                errors.append(f"line {lineno}: CHECK-BLOCK '{b}' not found in blocks {names}")
        elif kind == "CHECK-BLOCK-NOT":
            for n in (n for n in blocks if re.search(a, n)):
                hits = [ln.strip() for ln in blocks[n] if re.search(b, ln)]
                if hits:
                    errors.append(f"line {lineno}: CHECK-BLOCK-NOT '{b}' matched in %{n}: {hits[0]}")
                    break
    return errors


def golden_output(sy_path, in_path, name, verbose):
    """Committed .out next to the test wins; otherwise compile the test as C
    on the host (sylib linked) and record stdout + exit code."""
    out_path = os.path.splitext(sy_path)[0] + ".out"
    if os.path.exists(out_path):
        with open(out_path, encoding="utf-8") as f:
            return f.read()
    host_bin = os.path.join(WORK, name + ".host")
    cc = run(["gcc", "-x", "c", "-O1", "-fwrapv", "-fcommon", "-include", SYLIB_H,
              sy_path, SYLIB_C, "-o", host_bin])
    if cc.returncode != 0:
        raise Failure("host golden compile failed:\n" + cc.stderr.decode(errors="replace"))
    try:
        res = run([host_bin], stdin_path=in_path)
    except subprocess.TimeoutExpired:
        raise Failure("host golden run timed out")
    if verbose:
        sys.stderr.write(res.stderr.decode(errors="replace"))
    return format_actual(res.stdout, res.returncode)


def format_actual(stdout_bytes, exit_code):
    """The competition convention: stdout, then the exit code on its own line."""
    text = stdout_bytes.decode(errors="replace")
    if text and not text.endswith("\n"):
        text += "\n"
    return text + str(exit_code & 0xFF) + "\n"


def outputs_equal(lhs, rhs):
    strip = lambda s: [ln.rstrip() for ln in s.rstrip("\n").split("\n")]
    return strip(lhs) == strip(rhs)


def run_ir_checks(sy_path, name, stage, checks):
    if not checks:
        return []
    dump_path = os.path.join(WORK, f"{name}.{stage}")
    env = os.environ.copy()
    env["LOOP_OPT_STATS"] = "1"
    res = run([COMPILER, sy_path, "-o", dump_path, f"-{stage}", "-O1"], env=env)
    if res.returncode != 0:
        return [f"IR dump compile failed (exit {res.returncode}):\n"
                + res.stderr.decode(errors="replace")[-500:]]
    with open(dump_path, encoding="utf-8") as f:
        dump_lines = f.read().splitlines()
    stats_lines = res.stderr.decode(errors="replace").splitlines()
    return apply_checks(checks, dump_lines, split_blocks(dump_lines), stats_lines)


def run_correctness(sy_path, in_path, name, golden, targets, opts):
    errors = []
    for target in targets:
        cfg = TARGETS[target]
        for opt in opts:
            tag = f"{name}.{target}.O{opt}"
            s_path = os.path.join(WORK, tag + ".s")
            elf_path = os.path.join(WORK, tag + ".elf")
            res = run([COMPILER, sy_path, "-o", s_path, "-S", cfg["flag"], f"-O{opt}"])
            if res.returncode != 0:
                errors.append(f"[{target} -O{opt}] compile failed (exit {res.returncode})")
                continue
            res = run([cfg["gcc"], "-static", s_path, SYLIB_C, "-I", os.path.dirname(SYLIB_H),
                       "-o", elf_path])
            if res.returncode != 0:
                errors.append(f"[{target} -O{opt}] assemble/link failed:\n"
                              + res.stderr.decode(errors="replace")[-500:])
                continue
            try:
                res = run([cfg["qemu"], elf_path], stdin_path=in_path, timeout=60)
            except subprocess.TimeoutExpired:
                errors.append(f"[{target} -O{opt}] qemu run timed out")
                continue
            actual = format_actual(res.stdout, res.returncode)
            if not outputs_equal(actual, golden):
                errors.append(f"[{target} -O{opt}] wrong output\n"
                              f"  expected: {golden!r}\n  actual:   {actual!r}")
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--filter", default="", help="run only tests whose path contains this")
    parser.add_argument("--targets", default="riscv,aarch64")
    parser.add_argument("--opts", default="0,1", help="comma-separated -O levels for correctness")
    parser.add_argument("--ir-only", action="store_true", help="skip qemu correctness runs")
    parser.add_argument("--verbose", action="store_true")
    args = parser.parse_args()

    targets = [t for t in args.targets.split(",") if t]
    for t in targets:
        if t not in TARGETS:
            sys.exit(f"unknown target '{t}'")
    opts = [o for o in args.opts.split(",") if o]

    os.makedirs(WORK, exist_ok=True)
    tests = []
    for dirpath, _, filenames in os.walk(TESTDIR):
        for fn in sorted(filenames):
            if fn.endswith(".sy"):
                tests.append(os.path.join(dirpath, fn))
    tests = sorted(t for t in tests if args.filter in os.path.relpath(t, TESTDIR))
    if not tests:
        sys.exit(f"no tests found under {TESTDIR} (filter: '{args.filter}')")

    passed, failed = 0, []
    for sy_path in tests:
        rel = os.path.relpath(sy_path, TESTDIR)
        name = rel[:-3].replace(os.sep, "_")
        in_path = os.path.splitext(sy_path)[0] + ".in"
        if not os.path.exists(in_path):
            in_path = None
        errors = []
        try:
            stage, checks = parse_directives(sy_path)
            errors += run_ir_checks(sy_path, name, stage, checks)
            if not args.ir_only:
                golden = golden_output(sy_path, in_path, name, args.verbose)
                errors += run_correctness(sy_path, in_path, name, golden, targets, opts)
        except Failure as e:
            errors.append(str(e))
        if errors:
            failed.append(rel)
            print(f"FAIL {rel}")
            for e in errors:
                print("     " + e.replace("\n", "\n     "))
        else:
            passed += 1
            if args.verbose:
                print(f"PASS {rel}")
    print(f"# directed: pass={passed} fail={len(failed)}"
          + (f" -- {' '.join(failed)}" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
